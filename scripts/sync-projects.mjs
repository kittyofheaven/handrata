/**
 * Regenerates src/data/repos.generated.ts from GitHub.
 *
 * Run manually, commit the result: the site is static and public, so it must
 * never hold a token or hit the API at request time.
 *
 *   node scripts/sync-projects.mjs
 *
 * Requires the `gh` CLI authenticated as the account that owns the repos
 * (scope `repo`, so private repositories are visible).
 *
 * Private repos are recorded by name only — `url` is forced to null so no
 * generated code can link a visitor to a 404.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const OWNER = "kittyofheaven";

/** Repos that aren't projects: profile config, empty placeholders. */
const NOT_A_PROJECT = new Set([OWNER, `${OWNER}.github.io`]);

const raw = execFileSync(
  "gh",
  [
    "repo",
    "list",
    OWNER,
    "--limit",
    "200",
    "--json",
    "name,description,primaryLanguage,updatedAt,isPrivate,isArchived,url,homepageUrl,stargazerCount",
  ],
  { encoding: "utf8", maxBuffer: 20 * 1024 * 1024 }
);

const repos = JSON.parse(raw)
  .filter((r) => !NOT_A_PROJECT.has(r.name))
  .map((r) => ({
    name: r.name,
    description: r.description || null,
    language: r.primaryLanguage?.name || null,
    updatedAt: r.updatedAt.slice(0, 10),
    isPrivate: r.isPrivate,
    stars: r.stargazerCount ?? 0,
    url: r.isPrivate ? null : r.url,
    homepage: r.homepageUrl || null,
  }))
  .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));

const file = `// GENERATED by scripts/sync-projects.mjs — do not edit by hand.
// Private repositories carry \`url: null\` so nothing can link to them.

export type Repo = {
  name: string;
  description: string | null;
  language: string | null;
  updatedAt: string;
  isPrivate: boolean;
  stars: number;
  url: string | null;
  homepage: string | null;
};

export const repos: Repo[] = ${JSON.stringify(repos, null, 2)};
`;

writeFileSync(new URL("../src/data/repos.generated.ts", import.meta.url), file);

const priv = repos.filter((r) => r.isPrivate).length;
console.log(
  `Wrote ${repos.length} repos (${repos.length - priv} public, ${priv} private) to src/data/repos.generated.ts`
);
